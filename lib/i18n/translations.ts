export function getLocalizedProduct(product: any, lang: Language) {
  if (lang === "th" || !localizedProducts[product?.slug]?.en) {
    return product;
  }
  const enData = localizedProducts[product.slug].en;
  return {
    ...product,
    name: enData.name || product.name,
    tagline: enData.tagline || product.tagline,
    shortDescription: enData.shortDescription || product.shortDescription,
    description: enData.description || product.description,
    problemsTitle: enData.problemsTitle || product.problemsTitle,
    problemsDescription: enData.problemsDescription || product.problemsDescription,
    solutionTitle: enData.solutionTitle || product.solutionTitle,
    solutionDescription: enData.solutionDescription || product.solutionDescription,
    featuresTitle: enData.featuresTitle || product.featuresTitle,
    pricingNote: enData.pricingNote || product.pricingNote,
    demoNote: enData.demoNote || product.demoNote,
    problems: enData.problems && product.problems ? product.problems.map((p: any, idx: number) => ({
      ...p,
      problemText: enData.problems?.[idx]?.problemText || p.problemText,
      impactText: enData.problems?.[idx]?.impactText || p.impactText,
    })) : product.problems,
    features: enData.features && product.features ? product.features.map((f: any, idx: number) => ({
      ...f,
      title: enData.features?.[idx]?.title || f.title,
      description: enData.features?.[idx]?.description || f.description,
      badge: enData.features?.[idx]?.badge || f.badge,
    })) : product.features,
    badges: enData.badges && product.badges ? product.badges.map((b: any, idx: number) => ({
      ...b,
      badgeText: enData.badges?.[idx]?.badgeText || b.badgeText,
    })) : product.badges,
  };
}

